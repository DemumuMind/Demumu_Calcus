tsLines.push("  const abs = Math.abs(n);");
tsLines.push("  if (abs < 1e-6 || abs >= 1e9) {");
tsLines.push("    return n.toExponential(4).replace(/e([+-]?)(\\\\d+)/, '×10^$1$2');");
tsLines.push("  }");
tsLines.push("  let s = n.toFixed(6);");
tsLines.push("  if (s.includes('.')) {");
tsLines.push("    s = s.replace(/\\.?0+$/, '');");
tsLines.push("  }");
tsLines.push("  return s;");
tsLines.push("}");
